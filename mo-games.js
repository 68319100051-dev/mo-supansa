class MoGames {
    constructor() {
        this.storageKey = 'mo_games_v1';
        this.data = this.load();
        this.active = null;   // { id, startedAt, lastAt }
    }

    load() {
        try {
            const saved = JSON.parse(localStorage.getItem(this.storageKey) || 'null');
            if (saved) return saved;
        } catch (e) {}
        return { askedDaily: [], lastDaily: '' };
    }

    save() {
        try { localStorage.setItem(this.storageKey, JSON.stringify(this.data)); } catch (e) {}
    }

    /**
     * คำถามประจำวัน: ยังไม่ถามวันนี้ + หลัง 10 โมง → คืนคำถาม (แล้วจดว่าถามแล้ว)
     */
    takeDailyQuestion() {
        const today = new Date().toDateString();
        if (this.data.lastDaily === today || new Date().getHours() < 10) return null;
        let pool = MO_DAILY_QUESTIONS.filter((_, i) => !this.data.askedDaily.includes(i));
        if (!pool.length) {
            this.data.askedDaily = [];
            pool = MO_DAILY_QUESTIONS;
        }
        const q = pool[Math.floor(Math.random() * pool.length)];
        this.data.askedDaily.push(MO_DAILY_QUESTIONS.indexOf(q));
        this.data.lastDaily = today;
        this.save();
        return q;
    }

    start(id) {
        this.active = { id, startedAt: Date.now(), lastAt: Date.now() };
        return MO_GAMES[id];
    }

    /**
     * โน้ตบอก AI ระหว่างเล่น (จบเมื่อพิมพ์เลิกเล่น หรือเงียบเกิน 30 นาที)
     */
    noteFor(text) {
        const a = this.active;
        if (!a) return '';
        if (Date.now() - a.lastAt > 30 * 60000) {
            this.active = null;
            return '';
        }
        const game = MO_GAMES[a.id];
        if (/เลิกเล่น|พอแล้ว|ไม่เล่นแล้ว|หยุดเล่น|จบเกม/.test(text)) {
            this.active = null;
            return `[ข้อความระบบ: เองขอจบเกม "${game.name}" — สรุปผลสั้นๆ แบบสนุกแล้วคุยต่อปกติ]\n`;
        }
        a.lastAt = Date.now();
        return `[ข้อความระบบ: กำลังเล่นเกม "${game.name}" อยู่ กติกา: ${game.rules} — ดูสถานะเกมจากแชทข้างบนแล้วเล่นต่อ]\n`;
    }
}

